"""Generate the example pages of the docs from the examples on pele.run.

Fetches https://pele.run/examples.md, writes one page per diagram type to
docs/examples/ and updates the example navigation in zensical.toml.

Run it with ``uv run scripts/sync_pele_examples.py``.
"""

from __future__ import annotations

import json
import re
import textwrap
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

PELE_SITE = "https://pele.run"
ROOT = Path(__file__).resolve().parent.parent
EXAMPLES_DIR = ROOT / "docs" / "examples"
CONFIG_FILE = ROOT / "zensical.toml"

NAV_START = "# Example pages, generated by scripts/sync_pele_examples.py: start"
NAV_END = "# Example pages, generated by scripts/sync_pele_examples.py: end"

GENERATED_NOTICE = (
    "<!-- Generated by scripts/sync_pele_examples.py from {url}. Do not edit. -->"
)

_FRONTMATTER = re.compile(r"\A---\n(?P<body>.*?)\n---\n", re.DOTALL)
_SECTION_HEADING = re.compile(r"^## (?P<title>.+)$", re.MULTILINE)
_MERMAID_FENCE = re.compile(
    r"^```mermaid\n(?P<source>.*?)^```$", re.MULTILINE | re.DOTALL
)
_ALL_EXAMPLES_LINK = re.compile(r"\[All examples\]\(/examples/(?P<slug>[\w-]+)\)")
_DESCRIPTION = re.compile(r"^description: (?P<text>.+)$", re.MULTILINE)


@dataclass(frozen=True)
class DiagramType:
    """A diagram type with its examples, as listed on pele.run/examples."""

    slug: str
    title: str
    sources: tuple[str, ...]
    description: str = ""

    @property
    def pele_url(self) -> str:
        """Page of this diagram type on pele.run."""
        return f"{PELE_SITE}/examples/{self.slug}"


def fetch_text(url: str) -> str:
    """Download a text document."""
    request = urllib.request.Request(url, headers={"User-Agent": "zensical-pele"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def parse_examples_page(markdown: str) -> list[DiagramType]:
    """Split pele.run/examples.md into diagram types and their example sources."""
    markdown = _FRONTMATTER.sub("", markdown, count=1)
    headings = list(_SECTION_HEADING.finditer(markdown))
    diagram_types = []
    for heading, next_heading in zip(headings, [*headings[1:], None], strict=True):
        end = next_heading.start() if next_heading else len(markdown)
        section = markdown[heading.end() : end]
        link = _ALL_EXAMPLES_LINK.search(section)
        sources = tuple(m["source"] for m in _MERMAID_FENCE.finditer(section))
        if link is None or not sources:
            continue
        diagram_types.append(
            DiagramType(slug=link["slug"], title=heading["title"], sources=sources)
        )
    return diagram_types


def fetch_description(diagram_type: DiagramType) -> DiagramType:
    """Read the one-line description from the diagram type's own page."""
    page = fetch_text(f"{diagram_type.pele_url}.md")
    frontmatter = _FRONTMATTER.match(page)
    match = _DESCRIPTION.search(frontmatter["body"]) if frontmatter else None
    description = match["text"].strip() if match else ""
    return DiagramType(
        slug=diagram_type.slug,
        title=diagram_type.title,
        sources=diagram_type.sources,
        description=description,
    )


def render_diagram_page(diagram_type: DiagramType) -> str:
    """Render the example page of one diagram type."""
    lines = [
        "---",
        f"title: {json.dumps(diagram_type.title)}",
        f"description: {json.dumps(diagram_type.description)}",
        "---",
        "",
        GENERATED_NOTICE.format(url=f"{PELE_SITE}/examples"),
        "",
        f"# {diagram_type.title}",
        "",
        diagram_type.description,
        "",
    ]
    for source in diagram_type.sources:
        diagram = f"```mermaid\n{source}```"
        lines += [
            '=== "Diagram"',
            "",
            textwrap.indent(diagram, "    "),
            "",
            '=== "Markdown"',
            "",
            textwrap.indent(f"````markdown\n{diagram}\n````", "    "),
            "",
        ]
    lines += [
        f"More {diagram_type.title.lower()} examples on "
        f"[pele.run]({diagram_type.pele_url}).",
        "",
    ]
    return "\n".join(lines)


def render_examples_index(diagram_types: list[DiagramType]) -> str:
    """Render the list of diagram types."""
    lines = [
        "---",
        "title: Examples",
        "description: Every diagram type that Pele renders.",
        "---",
        "",
        GENERATED_NOTICE.format(url=f"{PELE_SITE}/examples"),
        "",
        "# Examples",
        "",
        f"The examples from [pele.run]({PELE_SITE}/examples), rendered by",
        "zensical-pele. Each page has the diagram and its Markdown.",
        "",
    ]
    lines += [f"- [{t.title}]({t.slug}.md): {t.description}" for t in diagram_types]
    lines.append("")
    return "\n".join(lines)


def update_navigation(config: str, diagram_types: list[DiagramType]) -> str:
    """Replace the generated example entries in the zensical.toml navigation."""
    start, end = config.index(NAV_START), config.index(NAV_END)
    indent = " " * (start - config.rindex("\n", 0, start) - 1)
    entries = "".join(
        f'{indent}{{ "{t.title}" = "examples/{t.slug}.md" }},\n' for t in diagram_types
    )
    return config[: start + len(NAV_START)] + "\n" + entries + indent + config[end:]


def main() -> None:
    """Fetch the examples and regenerate the example pages."""
    diagram_types = parse_examples_page(fetch_text(f"{PELE_SITE}/examples.md"))
    with ThreadPoolExecutor(max_workers=8) as pool:
        diagram_types = list(pool.map(fetch_description, diagram_types))

    for page in EXAMPLES_DIR.glob("*.md"):
        page.unlink()
    EXAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    (EXAMPLES_DIR / "index.md").write_text(render_examples_index(diagram_types))
    for diagram_type in diagram_types:
        page = EXAMPLES_DIR / f"{diagram_type.slug}.md"
        page.write_text(render_diagram_page(diagram_type))

    CONFIG_FILE.write_text(update_navigation(CONFIG_FILE.read_text(), diagram_types))
    examples = sum(len(t.sources) for t in diagram_types)
    print(f"Wrote {len(diagram_types)} diagram types with {examples} examples")


if __name__ == "__main__":
    main()
